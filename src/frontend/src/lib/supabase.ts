import { createClient } from '@supabase/supabase-js';
import type { VerifiedProduct, Supermarket, CollectorRun } from '../types';

const supabaseUrl = import.meta.env.VITE_SUPABASE_URL;
const supabaseAnonKey = import.meta.env.VITE_SUPABASE_ANON_KEY;

export const supabase = (supabaseUrl && supabaseAnonKey && !supabaseUrl.includes('your-project'))
  ? createClient(supabaseUrl, supabaseAnonKey)
  : null;

export async function fetchVerifiedCatalog(): Promise<VerifiedProduct[]> {
  try {
    // 1. If Supabase is configured, fetch from Supabase
    if (supabase) {
      const { data, error } = await supabase
        .from('products')
        .select(`
          id,
          canonical_name,
          brand,
          barcode,
          quantity,
          unit,
          category,
          store_products (
            id,
            supermarket_id,
            source_product_id,
            source_product_name,
            product_url,
            image_url,
            availability_status,
            last_observed_at,
            supermarkets (
              id,
              name,
              slug
            ),
            price_observations (
              price,
              original_price,
              currency,
              observed_at
            )
          )
        `);

      if (!error && data && data.length > 0) {
        // Transform Supabase relational data into VerifiedProduct view
        return data.map((p: any) => {
          const offers = (p.store_products || []).map((sp: any) => {
            const obs = (sp.price_observations || []).sort(
              (a: any, b: any) => new Date(b.observed_at).getTime() - new Date(a.observed_at).getTime()
            );
            const latest = obs[0];
            return {
              StoreProductId: sp.id,
              SupermarketId: sp.supermarket_id,
              SupermarketName: sp.supermarkets?.name || 'Unknown',
              SupermarketSlug: sp.supermarkets?.slug || 'unknown',
              SourceProductId: sp.source_product_id,
              SourceProductName: sp.source_product_name,
              ProductUrl: sp.product_url,
              ImageUrl: sp.image_url,
              AvailabilityStatus: sp.availability_status,
              LastObservedAt: sp.last_observed_at,
              CurrentPrice: latest?.price ?? 0,
              OriginalPrice: latest?.original_price ?? null,
              Currency: latest?.currency || 'LKR',
              PriceHistory: obs.map((o: any) => ({
                Price: o.price,
                OriginalPrice: o.original_price,
                ObservedAt: o.observed_at
              }))
            };
          }).filter((o: any) => o.CurrentPrice > 0);

          const prices = offers.map((o: any) => o.CurrentPrice);
          const minPrice = prices.length > 0 ? Math.min(...prices) : 0;
          const maxPrice = prices.length > 0 ? Math.max(...prices) : 0;
          const cheapest = offers.find((o: any) => o.CurrentPrice === minPrice);

          return {
            Id: p.id,
            CanonicalName: p.canonical_name,
            Brand: p.brand,
            Barcode: p.barcode,
            Quantity: p.quantity,
            Unit: p.unit,
            Category: p.category,
            OffersCount: offers.length,
            MinPrice: minPrice,
            MaxPrice: maxPrice,
            PriceDifference: maxPrice - minPrice,
            CheapestSupermarket: cheapest?.SupermarketName || null,
            Offers: offers
          };
        });
      }
    }

    // 2. Load directly from verified static JSON generated by the .NET collector
    const resp = await fetch('/data/verified_catalog.json');
    if (!resp.ok) {
      console.warn('verified_catalog.json not yet available. Database may be empty.');
      return [];
    }
    const catalog: VerifiedProduct[] = await resp.json();
    return catalog;
  } catch (err) {
    console.error('Error loading verified catalog:', err);
    return [];
  }
}

export async function fetchSupermarkets(): Promise<Supermarket[]> {
  try {
    if (supabase) {
      const { data, error } = await supabase.from('supermarkets').select('*');
      if (!error && data && data.length > 0) {
        return data.map((s: any) => ({
          Id: s.id,
          Name: s.name,
          Slug: s.slug,
          WebsiteUrl: s.website_url,
          IntegrationStatus: s.integration_status,
          StatusReason: s.status_reason,
          CreatedAt: s.created_at
        }));
      }
    }

    const resp = await fetch('/data/supermarkets.json');
    if (!resp.ok) return [];
    return await resp.json();
  } catch (err) {
    console.error('Error loading supermarkets:', err);
    return [];
  }
}

export async function fetchCollectorRuns(): Promise<CollectorRun[]> {
  try {
    if (supabase) {
      const { data, error } = await supabase
        .from('collector_runs')
        .select('*')
        .order('started_at', { ascending: false })
        .limit(20);

      if (!error && data && data.length > 0) {
        return data.map((r: any) => ({
          Id: r.id,
          SupermarketId: r.supermarket_id,
          StartedAt: r.started_at,
          FinishedAt: r.finished_at,
          Status: r.status,
          ProductsChecked: r.products_checked,
          ProductsUpdated: r.products_updated,
          ErrorMessage: r.error_message
        }));
      }
    }

    const resp = await fetch('/data/collector_runs.json');
    if (!resp.ok) return [];
    return await resp.json();
  } catch (err) {
    console.error('Error loading collector runs:', err);
    return [];
  }
}
